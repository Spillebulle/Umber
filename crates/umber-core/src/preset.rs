//! The brush library: named, attributed presets, the set Umber ships with, and
//! the user's own set on disk.
//!
//! A preset is more than `{ name, brush }` because a library assembled from
//! several sources has to answer three questions the app cannot answer for
//! itself:
//!
//! - **Which brush is this?** — a stable [`BrushPreset::id`], so a saved
//!   selection survives a rename and so importing the same pack twice does not
//!   silently replace an edited copy.
//! - **Where did it come from?** — a [`Credit`], which is what makes shipping
//!   CC-BY material legal and CC0 material honest.
//! - **Where does it belong in the picker?** — a free-form
//!   [`BrushPreset::category`], because a flat list of two hundred brushes is
//!   not usable, and a [`BrushPreset::collection`] over the top of it for where
//!   the *user* has since decided it belongs.
//!
//! That last one has a second half, and it is the awkward one:
//! [`Library::collections`]. A user may file a **shipped** brush, and a shipped
//! preset lives in [`builtin`] — `include_str!`'d into the binary and replaced
//! wholesale by every update. So that choice cannot be written where the brush
//! is; it is recorded against the brush's stable id in the user's own
//! `brushes.ron`, which an update never touches.
//!
//! And a third half, for the collection with nothing in it yet:
//! [`Library::made_collections`]. Every collection Umber shows is otherwise
//! *derived* from some preset, so a collection somebody has just made — which
//! is the only state it can be in before a brush is dragged into it — has
//! nothing to be derived from and would not survive the next rebuild of the
//! merged list. It is written down instead, and [`UserLibrary::create_collection`]
//! is what makes one.
//!
//! Everything here is plain data: no GPU types, no file dialogs, no UI.

